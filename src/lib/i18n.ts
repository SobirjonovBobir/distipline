export type Locale = "uz" | "en" | "ru";

export function normalizeLocale(value: string | null | undefined): Locale {
  const v = (value || "uz").toLowerCase();
  if (v === "en" || v.startsWith("en-")) return "en";
  if (v === "ru" || v.startsWith("ru-")) return "ru";
  return "uz";
}

